// Helper to create student with valid cryptographic token
function createSeedStudent(
  id: string,
  regNo: string,
  firstName: string,
  lastName: string,
  address: string,
  mobileNo: string,
  email: string,
  nic: string,
  school: string,
  stream: string,
  academicYear: string,
  enrolledClassIds: string[],
  photoUrl: string,
  enrolledAt: string
): Student {
  const { token, signature } = generateSecureStudentQrToken(id, regNo, 1726000000000);
  return {
    id,
    regNo,
    firstName,
    lastName,
    address,
    mobileNo,
    email,
    nic,
    guardianName: `${lastName} Senior`,
    guardianPhone: mobileNo,
    school,
    stream,
    academicYear,
    enrolledClassIds,
    qrToken: token,
    qrSignature: signature,
    status: 'active',
    enrolledAt,
    photoUrl,
  };
}

